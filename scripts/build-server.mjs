#!/usr/bin/env node
// Builds self-contained orc-server bundles: a Node Single Executable Application + the platform's `claude` binary.
// Usage: node scripts/build-server.mjs [--sea-only] [target ...]   targets: darwin-arm64 darwin-x64 linux-x64 linux-arm64 win32-x64 win32-arm64 (default: this machine)
// --sea-only: just out/server/<target>/orc-server[.exe], no claude, tarball or bundles.json (the tests' Windows install).
// darwin targets need macOS (codesign); the rest build anywhere. Node is pinned to Electron's: the blob is built with that version and injected into each target's stock binary.
import { execFileSync } from 'child_process'
import { createHash } from 'crypto'
import { chmodSync, copyFileSync, createWriteStream, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'fs'
import { createRequire } from 'module'
import { join, resolve } from 'path'
import { pipeline } from 'stream/promises'

const require = createRequire(import.meta.url)
const NODE = '24.22.0' // = Electron 44.9's process.versions.node; bump together
const pkg = JSON.parse(readFileSync('package.json', 'utf-8'))
const sdkVersion = JSON.parse(readFileSync('node_modules/@anthropic-ai/claude-agent-sdk/package.json', 'utf-8')).version // the package's exports map hides package.json from require
const host = `${process.platform}-${process.arch}`
const seaOnly = process.argv.includes('--sea-only'), args = process.argv.slice(2).filter((a) => a !== '--sea-only')
const targets = args.length ? args : [host]
const out = resolve('out/server'), cache = join(out, 'cache')
mkdirSync(cache, { recursive: true })
const tar = process.platform === 'win32' ? join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'tar.exe') : 'tar' // Windows' bsdtar (reads zips), never Git's GNU tar
const sh = (cmd, args, opts = {}) => execFileSync(cmd, args, { stdio: 'inherit', ...opts })
const sha256 = (file) => createHash('sha256').update(readFileSync(file)).digest('hex')

async function download(url, to) {
  if (existsSync(to)) return
  console.log('fetch', url)
  const r = await fetch(url); if (!r.ok) throw new Error(`${url}: ${r.status}`)
  await pipeline(r.body, createWriteStream(to))
}
/** Stock `bin/node` for a target, checksum-verified against nodejs.org. */
async function nodeFor(target) {
  const win = target.startsWith('win32'), dir = join(cache, `node-${target}`), bin = join(dir, win ? 'node.exe' : 'node')
  if (existsSync(bin)) return bin
  const name = `node-v${NODE}-${win ? target.replace('win32', 'win') : target}`, ext = win ? 'zip' : 'tar.gz', archive = join(cache, `${name}.${ext}`), sums = join(cache, `SHASUMS256-${NODE}.txt`)
  await download(`https://nodejs.org/dist/v${NODE}/${name}.${ext}`, archive)
  await download(`https://nodejs.org/dist/v${NODE}/SHASUMS256.txt`, sums)
  const expected = readFileSync(sums, 'utf-8').split('\n').find((l) => l.endsWith(`${name}.${ext}`))?.split(/\s+/)[0]
  if (sha256(archive) !== expected) throw new Error(`checksum mismatch for ${name}`)
  mkdirSync(dir, { recursive: true })
  if (win && process.platform === 'linux') sh('unzip', ['-q', '-j', archive, `${name}/node.exe`, '-d', dir]) // GNU tar can't read zips
  else if (win) sh(tar, ['xf', archive, '-C', dir, '--strip-components=1', `${name}/node.exe`]) // bsdtar (macOS, Windows) reads them
  else sh(tar, ['xzf', archive, '-C', dir, '--strip-components=2', `${name}/bin/node`])
  return bin
}
/** The SDK platform package's `claude` for a target: the installed one, or fetched with npm pack. */
function claudeFor(target) {
  const exe = target.startsWith('win32') ? 'claude.exe' : 'claude'
  const local = join('node_modules/@anthropic-ai', `claude-agent-sdk-${target}`, exe)
  if (existsSync(local)) return local
  const dir = join(cache, `claude-${target}`), bin = join(dir, 'package', exe)
  if (!existsSync(bin)) {
    mkdirSync(dir, { recursive: true })
    const tgz = execFileSync('npm', ['pack', `@anthropic-ai/claude-agent-sdk-${target}@${sdkVersion}`, '--pack-destination', dir], { encoding: 'utf-8' }).trim()
    sh(tar, ['xzf', join(dir, tgz), '-C', dir])
  }
  return bin
}

// 1. One CJS file: the server bundle plus its chunks and the SDK wrapper; import.meta.url shimmed for createRequire.
const entry = join(out, 'orc-server.cjs'), shim = join(out, 'shim.js')
writeFileSync(shim, "export const __importMetaUrl = require('url').pathToFileURL(__filename).href\n")
require('esbuild').buildSync({ entryPoints: ['out/main/orc-server.js'], bundle: true, platform: 'node', target: `node${NODE.split('.')[0]}`, format: 'cjs', inject: [shim], define: { 'import.meta.url': '__importMetaUrl' }, outfile: entry, logLevel: 'warning' })
// 2. The blob, generated by the pinned Node (the runner's own platform) — platform-independent without snapshot/code cache.
const seaCfg = join(out, 'sea-config.json'), blob = join(out, 'sea.blob')
writeFileSync(seaCfg, JSON.stringify({ main: entry, output: blob, disableExperimentalSEAWarning: true, useCodeCache: false, useSnapshot: false }))
sh(await nodeFor(host), ['--experimental-sea-config', seaCfg])
// 3. Per target: inject, sign, add claude, tar, hash.
const bundles = {}
for (const t of targets) {
  const win = t.startsWith('win32'), server = win ? 'orc-server.exe' : 'orc-server', claude = win ? 'claude.exe' : 'claude'
  const dir = join(out, t), bin = join(dir, server)
  rmSync(dir, { recursive: true, force: true }); mkdirSync(dir, { recursive: true })
  copyFileSync(await nodeFor(t), bin); chmodSync(bin, 0o755)
  const mac = t.startsWith('darwin')
  if (mac) sh('codesign', ['--remove-signature', bin])
  sh(process.execPath, [require.resolve('postject/dist/cli.js'), bin, 'NODE_SEA_BLOB', blob, '--sentinel-fuse', 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2', ...(mac ? ['--macho-segment-name', 'NODE_SEA'] : [])]) // ELF, Mach-O and PE alike
  // ORC_SIGN_IDENTITY (the release's Developer ID): hardened runtime and a timestamp, as notarization requires of everything
  // inside Orc Offline, which carries these bundles; otherwise an ad-hoc signature, which Apple silicon needs to run at all.
  if (mac) sh('codesign', process.env.ORC_SIGN_IDENTITY ? ['--force', '--sign', process.env.ORC_SIGN_IDENTITY, '--options', 'runtime', '--timestamp', '--entitlements', 'build/entitlements.mac.plist', bin] : ['-s', '-', bin])
  if (seaOnly) continue
  copyFileSync(claudeFor(t), join(dir, claude)); chmodSync(join(dir, claude), 0o755)
  const tgz = join(out, `orc-server-${t}.tar.gz`)
  sh(tar, ['czf', tgz, '-C', dir, server, claude]) // Windows 10+ ships tar.exe, which unpacks this
  bundles[t] = { url: `https://github.com/yuvalino/orc/releases/download/v${pkg.version}/orc-server-${t}.tar.gz`, sha256: sha256(tgz) }
  console.log('built', tgz)
}
// The app ships bundles.json: the built targets' entries are merged into it (a release builds all four).
const manifest = JSON.parse(readFileSync('bundles.json', 'utf-8'))
if (!seaOnly) writeFileSync('bundles.json', JSON.stringify({ version: pkg.version, bundles: { ...manifest.bundles, ...bundles } }, null, 2) + '\n')
